-- PostgreSQL baseline for the CURRENT QuanNgon ORM (2026-11-01).
-- Connect to "quanngon" or the database configured by DB_URL first.
-- Run on an empty public schema, then run Insert_data_test.sql for demo data.
-- This is a baseline, not an ALTER/migration script for existing tables.
-- Derived from all 9 JPA entities using Spring Boot 4.1.1 / Hibernate 7.4.5.
-- No application.properties or Java entity changes are required.
-- For a manually managed schema, set ddl-auto=validate in your deployment
-- configuration after creating the tables.
--
-- Important ORM details:
--   Review.reviewID -> reviews.reviewid (not review_id).
--   Instant -> timestamp(6) with time zone.
--   LocalDateTime -> timestamp(6) without time zone.
--   Unspecified String length -> varchar(255), NOT text.
--   RefreshToken.refreshToken explicitly uses varchar(1024).
--   phone_contact is varchar(10), exactly as Eatery.java declares.
--   rejection_reason is nullable varchar(500); only the current rejection reason is stored.
--   Eatery.version is an ORM-managed optimistic lock counter, initially 0.
--   Review has no version/updated_at; created_at is refreshed on ORM insert/update.
--   Review.content supports 1000 characters; one review per user/eatery pair.
--   Favorite contains only id/user_id/eatery_id; lists sort by Favorite.id DESC.
--   One favorite per user/eatery pair; user/eatery removals cascade through JPA.
--   Account.createdAt is immutable; accounts.created_at also defaults to CURRENT_TIMESTAMP
--   for accounts created directly through SQL.
--   Account.sessionVersion is an application-managed session counter, initially 0.
--   Refresh tokens belong to the current session; there is no revoked flag.
--   categories.name_key is maintained by a DB trigger, not mapped by JPA.
--   category_name_key, its trigger and UNIQUE constraint are included below.
--   CascadeType.ALL/orphanRemoval are handled by Hibernate, not ON DELETE CASCADE.
--   CreationTimestamp/UpdateTimestamp and Builder defaults are Java behavior;
--   inserts via SQL must supply these required values explicitly unless a DB default exists.

BEGIN;

SET LOCAL search_path TO public;

-- Accent-insensitive name search; keep the original stored names unchanged.
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;

CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(255) NOT NULL CHECK (role IN ('ADMIN', 'USER')),
    active boolean NOT NULL,
    email_verified boolean NOT NULL,
    session_version bigint NOT NULL DEFAULT 0,
    created_at timestamp(6) with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(255) NOT NULL,
    account_id bigint UNIQUE,
    CONSTRAINT FKfm8rm8ks0kgj4fhlmmljkj17x
        FOREIGN KEY (account_id) REFERENCES accounts (id)
);

CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    name_key text NOT NULL,
    CONSTRAINT uk_categories_normalized_name UNIQUE (name_key)
);

-- Use one normalization rule for searching and enforcing name uniqueness.
CREATE OR REPLACE FUNCTION public.category_name_key(value text)
RETURNS text LANGUAGE sql STABLE STRICT
AS $$
    SELECT lower(public.unaccent(btrim(regexp_replace(value, '[[:space:]]+', ' ', 'g'))));
$$;

CREATE OR REPLACE FUNCTION public.set_category_name_key()
RETURNS trigger LANGUAGE plpgsql
AS $$
BEGIN
    NEW.name_key := public.category_name_key(NEW.name);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_categories_name_key
BEFORE INSERT OR UPDATE ON categories
FOR EACH ROW EXECUTE FUNCTION public.set_category_name_key();

CREATE TABLE addresses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    street varchar(255) NOT NULL,
    ward varchar(255) NOT NULL,
    province varchar(255) NOT NULL
);

CREATE TABLE eateries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint NOT NULL DEFAULT 0,
    name varchar(255) NOT NULL,
    phone_contact varchar(10) NOT NULL,
    content text NOT NULL,
    status varchar(255) NOT NULL
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'HIDDEN')),
    rejection_reason varchar(500),
    category_id bigint NOT NULL,
    user_id bigint NOT NULL,
    address_id bigint NOT NULL UNIQUE,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT FK89cat0h3gn790cfenc3xco25r
        FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT FK521nyfo00kpasor1jkyq2rdxb
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT FK6hc1i4kkpvcinx9a73aw0nbgt
        FOREIGN KEY (address_id) REFERENCES addresses (id)
);

CREATE TABLE favorites (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    eatery_id bigint NOT NULL,
    CONSTRAINT uk_favorites_user_eatery UNIQUE (user_id, eatery_id),
    CONSTRAINT fk_favorites_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_favorites_eatery FOREIGN KEY (eatery_id) REFERENCES eateries (id)
);

CREATE TABLE reviews (
    reviewid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_quantity integer NOT NULL,
    service_quantity integer NOT NULL,
    space integer NOT NULL,
    cleanliness integer NOT NULL,
    content varchar(1000),
    created_at timestamp(6) without time zone NOT NULL,
    user_id bigint NOT NULL,
    eatery_id bigint,
    CONSTRAINT uk_reviews_user_eatery UNIQUE (user_id, eatery_id),
    CONSTRAINT FKcgy7qjc1r99dp117y9en6lxye
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT FKhvx7c78ee0vvri1lmxemf2vmb
        FOREIGN KEY (eatery_id) REFERENCES eateries (id)
);

CREATE TABLE images (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id varchar(255) NOT NULL UNIQUE,
    url varchar(255) NOT NULL,
    type varchar(20) NOT NULL CHECK (type IN ('THUMBNAIL', 'GALLERY')),
    eatery_id bigint,
    review_id bigint,
    CONSTRAINT FKonhyiqqfn8tjynbt99n1f3g5
        FOREIGN KEY (eatery_id) REFERENCES eateries (id),
    CONSTRAINT FKldf2s8wlcsqgmmrokc6syxw5q
        FOREIGN KEY (review_id) REFERENCES reviews (reviewid)
);

CREATE TABLE refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refresh_token varchar(1024) NOT NULL UNIQUE,
    account_id bigint NOT NULL,
    expiry_date timestamp(6) with time zone NOT NULL,
    CONSTRAINT FK6fm1gdbsrg5h8r5e3voiu6bo9
        FOREIGN KEY (account_id) REFERENCES accounts (id)
);

COMMIT;
